import 'package:flutter/material.dart';

// --- Charadas ----------------------------------------------------------------

enum CardDifficulty {
  easy('Fácil', 1),
  medium('Media', 2),
  hard('Difícil', 3);

  const CardDifficulty(this.label, this.points);

  final String label;

  /// Puntos que vale acertar una carta de esta dificultad.
  final int points;
}

@immutable
class CharadesCard {
  const CharadesCard({
    required this.word,
    required this.hint,
    required this.category,
    required this.icon,
    this.difficulty = CardDifficulty.medium,
  });

  final String word;

  /// Indicación entre paréntesis bajo la palabra.
  final String hint;
  final String category;
  final IconData icon;
  final CardDifficulty difficulty;
}

/// Id del mazo armado por el grupo en la configuración.
const String kCustomCharadesDeck = 'custom';

/// Carta de una palabra escrita por el grupo ("Mazo personalizado").

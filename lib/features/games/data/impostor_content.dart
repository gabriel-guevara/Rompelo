/// Palabra secreta con su pista para el impostor (ajuste "Pista sutil").
@immutable
class ImpostorWord {
  const ImpostorWord(this.word, this.hint);

  final String word;

  /// Algo relacionado pero no obvio ("Pizza" → "Italia").
  final String hint;
}

@immutable
